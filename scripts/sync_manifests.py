def build_expected(plugin: dict) -> dict[str, str]:
    """Return {relative path: generated text} for every generated manifest."""
    name = plugin["name"]
    version = plugin["version"]
    description = plugin["description"]
    author = plugin.get("author") or {}
    author_name = author.get("name")

    def dump(obj: dict) -> str:
        return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"

    claude_plugin = {
        "name": name,
        "version": version,
        "description": description,
        "author": author,
        "repository": plugin.get("repository"),
        "license": plugin.get("license"),
    }
    claude_plugin = {k: v for k, v in claude_plugin.items() if v is not None}

    claude_marketplace = {
        "name": name,
        "owner": {"name": author_name},
        "metadata": {"description": BLURB, "version": version},
        "plugins": [
            {
                "name": name,
                "source": MARKETPLACE_SOURCE_PATH,
                "description": BLURB,
                "version": version,
            }
        ],
    }

    copilot_marketplace = {
        "name": name,
        "owner": {"name": author_name},
        "metadata": {"description": BLURB, "version": version},
        "plugins": [
            {
                "name": name,
                "description": BLURB,
                "version": version,
                "source": MARKETPLACE_SOURCE_PATH,
            }
        ],
    }

    codex_marketplace = {
        "name": name,
        "interface": {"displayName": codex_display_name(plugin)},
        "plugins": [
            {
                "name": name,
                "source": dict(CODEX_SOURCE_OBJECT),
                "policy": dict(CODEX_POLICY),
                "category": codex_category(plugin),
            }
        ],
    }

    antigravity_plugin = {
        "$schema": ANTIGRAVITY_SCHEMA,
        "name": name,
        "description": BLURB,
    }

    return {
        ".claude-plugin/plugin.json": dump(claude_plugin),
        ".claude-plugin/marketplace.json": dump(claude_marketplace),
        ".github/plugin/marketplace.json": dump(copilot_marketplace),
        ".agents/plugins/marketplace.json": dump(codex_marketplace),
        f"{ANTIGRAVITY_DIR}/plugin.json": dump(antigravity_plugin),
    }


