def check_drift(repo_root: str, expected: dict[str, str]) -> list[str]:
    problems: list[str] = []
    for rel, text in sorted(expected.items()):
        path = os.path.join(repo_root, rel)
        if os.path.islink(path):
            problems.append(
                f"{rel}: is a symlink; every generated manifest must be a regular file "
                "(run: python3 scripts/sync_manifests.py --write after removing the link)"
            )
            continue
        if not os.path.isfile(path):
            problems.append(f"{rel}: missing (run: python3 scripts/sync_manifests.py --write)")
            continue
        with open(path, "rb") as fh:
            actual = fh.read()
        if actual != text.encode("utf-8"):
            problems.append(f"{rel}: drifted from plugin.json (run: python3 scripts/sync_manifests.py --write)")

    link_path = os.path.join(repo_root, ANTIGRAVITY_DIR, ANTIGRAVITY_SKILLS_LINK)
    if not os.path.islink(link_path):
        problems.append(
            f"{ANTIGRAVITY_DIR}/{ANTIGRAVITY_SKILLS_LINK}: not a symlink to {ANTIGRAVITY_SKILLS_TARGET} "
            "(run: python3 scripts/sync_manifests.py --write; on Windows, enable core.symlinks)"
        )
    elif os.readlink(link_path) != ANTIGRAVITY_SKILLS_TARGET:
        problems.append(
            f"{ANTIGRAVITY_DIR}/{ANTIGRAVITY_SKILLS_LINK}: points at {os.readlink(link_path)}, "
            f"expected {ANTIGRAVITY_SKILLS_TARGET}"
        )
    elif not os.path.isdir(link_path):
        problems.append(
            f"{ANTIGRAVITY_DIR}/{ANTIGRAVITY_SKILLS_LINK}: dangling link (target {ANTIGRAVITY_SKILLS_TARGET} missing)"
        )
    return problems


def check_surface(repo_root: str) -> list[str]:
    """Nothing client-visible may appear outside the set this generator owns."""
    problems: list[str] = []
    for entry in FORBIDDEN_ROOT_ARTEFACTS:
        if os.path.lexists(os.path.join(repo_root, entry)):
            problems.append(
                f"{entry}: client-visible artefact outside the generated manifest set "
                "(hooks/MCP/commands/rules are not part of this package; if the addition is "
                "deliberate, ship it in a reviewed PR that updates FORBIDDEN_ROOT_ARTEFACTS)"
            )
    for rel, allowed in sorted(GENERATED_DIRS.items()):
        directory = os.path.join(repo_root, rel)
        if not os.path.isdir(directory):
            problems.append(f"{rel}: missing directory")
            continue
        unexpected = sorted(name for name in os.listdir(directory) if name not in allowed)
        if unexpected:
            problems.append(
                f"{rel}: unexpected entries {unexpected}; the generator owns this directory "
                f"(expected {sorted(allowed)})"
            )
    return problems


def load_json(path: str, rel: str, problems: list[str]) -> dict | None:
    if not os.path.exists(path):
        problems.append(f"{rel}: missing")
        return None
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except json.JSONDecodeError as exc:
        problems.append(f"{rel}: invalid JSON ({exc})")
        return None
    if not isinstance(data, dict):
        problems.append(f"{rel}: top level must be a JSON object, found {type(data).__name__}")
        return None
    return data


def require_str(obj: dict, key: str, label: str, problems: list[str]) -> None:
    if not isinstance(obj.get(key), str) or not obj.get(key, "").strip():
        problems.append(f"{label}: {key} must be a non-empty string, found {obj.get(key)!r}")


def require_entries(container, label: str, problems: list[str]) -> list[dict]:
    if not isinstance(container, list) or not container:
        problems.append(f"{label}: must be a non-empty list")
        return []
    entries = []
    for index, entry in enumerate(container):
        if not isinstance(entry, dict):
            problems.append(f"{label}[{index}]: must be an object, found {type(entry).__name__}")
            continue
        entries.append(entry)
    return entries


def resolves_to_plugin(repo_root: str, rel_path: str) -> bool:
    target = os.path.join(repo_root, rel_path)
    return os.path.isfile(os.path.join(target, "plugin.json"))


def validate(repo_root: str, plugin: dict) -> list[str]:
    """Structural checks, one per harness, from the Phase 0 doc table on issue #17."""
    problems: list[str] = []
    name = plugin["name"]
    version = plugin["version"]

    def path_of(rel: str) -> str:
        return os.path.join(repo_root, rel)

    # --- Claude Code plugin manifest -------------------------------------
    rel = ".claude-plugin/plugin.json"
    claude_plugin = load_json(path_of(rel), rel, problems)
    if claude_plugin is not None:
        for key in ("name", "version", "description", "author"):
            if key not in claude_plugin:
                problems.append(f"{rel}: missing required field {key!r}")
        for key in ("name", "version", "description", "repository", "license"):
            if key in claude_plugin:
                require_str(claude_plugin, key, rel, problems)
        if "author" in claude_plugin:
            if not isinstance(claude_plugin["author"], dict):
                problems.append(f"{rel}: author must be an object")
            else:
                require_str(claude_plugin["author"], "name", f"{rel} author", problems)
        if claude_plugin.get("name") != name:
            problems.append(f"{rel}: name {claude_plugin.get('name')!r} != plugin.json {name!r}")
        if claude_plugin.get("version") != version:
            problems.append(f"{rel}: version {claude_plugin.get('version')!r} != plugin.json {version!r}")

    # --- Claude + Copilot marketplaces -----------------------------------
    for rel in (".claude-plugin/marketplace.json", ".github/plugin/marketplace.json"):
        market = load_json(path_of(rel), rel, problems)
        if market is None:
            continue
        require_str(market, "name", rel, problems)
        if isinstance(market.get("name"), str) and not KEBAB.fullmatch(market["name"]):
            problems.append(f"{rel}: marketplace name {market['name']!r} is not kebab-case")
        owner = market.get("owner")
        if not isinstance(owner, dict):
            problems.append(f"{rel}: owner must be an object with a name (required by the Claude/Copilot schemas)")
        else:
            require_str(owner, "name", f"{rel} owner", problems)
        metadata = market.get("metadata")
        if metadata is not None:
            if not isinstance(metadata, dict):
                problems.append(f"{rel}: metadata must be an object")
            else:
                require_str(metadata, "description", f"{rel} metadata", problems)
                if metadata.get("version") != version:
                    problems.append(
                        f"{rel}: metadata.version {metadata.get('version')!r} != plugin.json {version!r}"
                    )
        for entry in require_entries(market.get("plugins"), f"{rel} plugins", problems):
            require_str(entry, "name", f"{rel} plugins[]", problems)
            if entry.get("name") != name:
                problems.append(f"{rel}: entry name {entry.get('name')!r} != plugin.json {name!r}")
            if entry.get("version") != version:
                problems.append(f"{rel}: entry version {entry.get('version')!r} != plugin.json {version!r}")
            source = entry.get("source")
            if not isinstance(source, str):
                problems.append(
                    f"{rel}: plugins[].source must be a relative path string here "
                    "(this project points every client at the package root)"
                )
            elif not resolves_to_plugin(repo_root, source):
                problems.append(f"{rel}: source {source!r} does not resolve to a plugin (no plugin.json)")

    # --- Codex marketplace ----------------------------------------------
    rel = ".agents/plugins/marketplace.json"
    codex = load_json(path_of(rel), rel, problems)
    if codex is not None:
        require_str(codex, "name", rel, problems)
        interface = codex.get("interface")
        if not isinstance(interface, dict):
            problems.append(f"{rel}: interface must be an object")
        else:
            require_str(interface, "displayName", f"{rel} interface", problems)
        for entry in require_entries(codex.get("plugins"), f"{rel} plugins", problems):
            label = f"{rel} plugins[]"
            require_str(entry, "name", label, problems)
            require_str(entry, "category", label, problems)
            source = entry.get("source")
            if (
                not isinstance(source, dict)
                or source.get("source") != "local"
                or not isinstance(source.get("path"), str)
                or not source["path"].startswith("./")
            ):
                problems.append(f"{label}: source must be {{'source': 'local', 'path': './...'}}")
            elif not resolves_to_plugin(repo_root, source["path"]):
                problems.append(f"{label}: path {source['path']!r} does not resolve to a plugin (no plugin.json)")
            policy = entry.get("policy")
            if not isinstance(policy, dict):
                problems.append(f"{label}: policy must be an object")
            else:
                if policy.get("installation") not in ("AVAILABLE", "INSTALLED_BY_DEFAULT", "NOT_AVAILABLE"):
                    problems.append(
                        f"{label}: policy.installation must be one of "
                        "AVAILABLE/INSTALLED_BY_DEFAULT/NOT_AVAILABLE"
                    )
                require_str(policy, "authentication", f"{label} policy", problems)

    # --- Antigravity workspace plugin ------------------------------------
    rel = f"{ANTIGRAVITY_DIR}/plugin.json"
    anti = load_json(path_of(rel), rel, problems)
    if anti is not None:
        allowed = {"$schema", "name", "description"}
        extra = set(anti) - allowed
        if extra:
            problems.append(
                f"{rel}: unsupported keys {sorted(extra)} "
                "(the Antigravity CLI schema sets additionalProperties: false)"
            )
        if anti.get("$schema") != ANTIGRAVITY_SCHEMA:
            problems.append(f"{rel}: $schema must be {ANTIGRAVITY_SCHEMA}")
        require_str(anti, "description", rel, problems)
        if not isinstance(anti.get("name"), str) or not ANTIGRAVITY_NAME.fullmatch(anti.get("name", "")):
            problems.append(f"{rel}: name must match ^[a-zA-Z0-9-_]+$")
        elif anti.get("name") != name:
            problems.append(f"{rel}: name {anti.get('name')!r} != plugin.json {name!r}")

        link = path_of(f"{ANTIGRAVITY_DIR}/{ANTIGRAVITY_SKILLS_LINK}")
        if not os.path.isdir(link):
            problems.append(f"{ANTIGRAVITY_DIR}/{ANTIGRAVITY_SKILLS_LINK}: does not resolve to a directory")
        elif not os.path.isfile(os.path.join(link, name, "SKILL.md")):
            problems.append(f"{ANTIGRAVITY_DIR}/{ANTIGRAVITY_SKILLS_LINK}: missing {name}/SKILL.md")

        entries = sorted(os.listdir(path_of(ANTIGRAVITY_DIR)))
        if entries != sorted(["plugin.json", ANTIGRAVITY_SKILLS_LINK]):
            problems.append(
                f"{ANTIGRAVITY_DIR}: expected exactly plugin.json + {ANTIGRAVITY_SKILLS_LINK}, found {entries}"
            )

    return problems


