def write_all(repo_root: str, expected: dict[str, str]) -> list[str]:
    written: list[str] = []
    for rel, text in sorted(expected.items()):
        path = os.path.join(repo_root, rel)
        if os.path.islink(path):
            guard_fail(
                f"{rel}: is a symlink and is never written through "
                "(remove it first; on Windows, clone with core.symlinks enabled)"
            )
        if os.path.isdir(path):
            guard_fail(f"{rel}: is a directory, expected a regular file")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        payload = text.encode("utf-8")
        if os.path.isfile(path):
            with open(path, "rb") as fh:
                if fh.read() == payload:
                    continue
        with open(path, "wb") as fh:
            fh.write(payload)
        written.append(rel)

    link_dir = os.path.join(repo_root, ANTIGRAVITY_DIR)
    link_path = os.path.join(link_dir, ANTIGRAVITY_SKILLS_LINK)
    os.makedirs(link_dir, exist_ok=True)
    if os.path.islink(link_path):
        if os.readlink(link_path) != ANTIGRAVITY_SKILLS_TARGET:
            os.remove(link_path)
    if not os.path.islink(link_path):
        if os.path.lexists(link_path):
            guard_fail(
                f"{ANTIGRAVITY_DIR}/{ANTIGRAVITY_SKILLS_LINK}: exists and is not a symlink; refusing to "
                "overwrite. On Windows, clone with core.symlinks enabled."
            )
        try:
            os.symlink(ANTIGRAVITY_SKILLS_TARGET, link_path)
        except OSError as exc:
            guard_fail(
                f"{ANTIGRAVITY_DIR}/{ANTIGRAVITY_SKILLS_LINK}: cannot create symlink ({exc}); "
                "on Windows, developer mode or core.symlinks is required"
            )
        written.append(f"{ANTIGRAVITY_DIR}/{ANTIGRAVITY_SKILLS_LINK} (symlink)")
    return written


