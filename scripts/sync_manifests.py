#!/usr/bin/env python3
"""Keep every client manifest in sync with the package's single source of truth.

Source of truth: ./plugin.json — the Agent Plugins 1.0 portable manifest at the
package root. Identity (name, version, description, author, repository, license)
is read from there and never re-typed in a client adapter.

Generated files (never edit these by hand — run this script instead):

  .claude-plugin/plugin.json                       Claude Code plugin manifest
  .claude-plugin/marketplace.json                  Claude Code marketplace, also consumed by
                                                   VS Code via chat.plugins.marketplaces
  .github/plugin/marketplace.json                  GitHub Copilot CLI marketplace
  .agents/plugins/marketplace.json                 Codex CLI repo marketplace
  .agents/plugins/editorial-recension/plugin.json  Google Antigravity workspace plugin marker
  .agents/plugins/editorial-recension/skills       symlink -> ../../../skills

Propagation contract: the six identity keys above travel to the client manifests;
root-only keys (`keywords`, `extensions`) stay in the portable manifest. Codex
presentation data is *read* from `extensions["com.openai"]["interface"]` (with a
fallback to the flat `extensions["com.openai"]` shape) for the marketplace label.

Modes:

  (no flags)    drift check + tree surface + structural validation; exit 1 on any problem
  --write       rewrite every generated file from the source of truth, then re-check
  --check       drift check + tree surface only
  --validate    structural validation only

The default mode and `--check` guard the tree (generated bytes, file types,
generator-owned directories, client-visible artefacts); `--validate` guards each
manifest's fields. CI runs both.

The drift check compares bytes on disk with generated bytes, so CRLF edits,
reformatting, key reordering and extra keys all fail; it also requires every
generated path to be a regular file (never a symlink), every generator-owned
directory to hold exactly the entries this script emits, and no hooks/MCP/command/
rule artefact to appear at the package root unnoticed. CI runs this script on every
push and pull request and re-runs `--write`, failing on any working-tree change,
tracked or not.

Standard library only, no network, no writes unless --write is passed.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from typing import NoReturn

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# ---------------------------------------------------------------------------
# Content that is not part of the portable manifest, kept in exactly one place.
# ---------------------------------------------------------------------------

# Marketplace listing copy. Rewritten into every marketplace file.
BLURB = (
    "Two-agent editing loop: an editor applies five named schemata, an evaluator "
    "scores blind before reading the editor's trace, and they loop until the text passes."
)

# Codex marketplace entry category, used only when the manifest carries none.
CODEX_CATEGORY = "Writing"

# Codex marketplace source: object form, as the OpenAI packaging docs specify
# ("Always include policy.installation, policy.authentication, and category").
CODEX_SOURCE_OBJECT = {"source": "local", "path": "./"}
CODEX_POLICY = {"installation": "AVAILABLE", "authentication": "ON_INSTALL"}

# Claude/Copilot marketplace source: path relative to the marketplace root.
MARKETPLACE_SOURCE_PATH = "./"

# Google Antigravity plugin marker schema (antigravity.google/docs/cli/plugins/).
# The vendor schema lists only name + description under additionalProperties:false,
# while the vendor's own manifest example ships $schema — we follow the example.
ANTIGRAVITY_SCHEMA = "https://antigravity.google/schemas/v1/plugin.json"

ANTIGRAVITY_DIR = ".agents/plugins/editorial-recension"
ANTIGRAVITY_SKILLS_LINK = "skills"
ANTIGRAVITY_SKILLS_TARGET = "../../../skills"

# Directories this script owns. Any other entry inside them is drift by definition.
GENERATED_DIRS = {
    ".claude-plugin": ("plugin.json", "marketplace.json"),
    ".github/plugin": ("marketplace.json",),
    ".agents/plugins": ("marketplace.json", "editorial-recension"),
}

# Client-visible artefacts that must never appear at the package root unnoticed:
# hooks, MCP servers, commands and rules execute or load on the user's machine, and
# they are not part of this package's contract. A deliberate addition belongs in a
# reviewed PR that also updates this list.
FORBIDDEN_ROOT_ARTEFACTS = (
    "hooks",
    "hooks.json",
    "mcp.json",
    ".mcp.json",
    "commands",
    "rules",
    ".codex-plugin",
    ".cursor-plugin",
    ".plugin",
    "openclaw.plugin.json",
    ".claude",
)

KEBAB = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
ANTIGRAVITY_NAME = re.compile(r"[a-zA-Z0-9-_]+")


class GuardInputError(Exception):
    """Raised for malformed repository state; reported as a message, never a traceback."""


def guard_fail(message: str) -> NoReturn:
    raise SystemExit(f"manifest guard: {message}")


# ---------------------------------------------------------------------------
# Source of truth
# ---------------------------------------------------------------------------


def read_json_object(path: str, label: str) -> dict:
    if os.path.islink(path):
        guard_fail(f"{label}: is a symlink, expected a regular file")
    if os.path.isdir(path):
        guard_fail(f"{label}: is a directory, expected a regular file")
    if not os.path.exists(path):
        guard_fail(f"{label}: not found")
    try:
        with open(path, "rb") as fh:
            data = json.loads(fh.read().decode("utf-8"))
    except UnicodeDecodeError as exc:
        guard_fail(f"{label}: not valid UTF-8 ({exc})")
    except json.JSONDecodeError as exc:
        guard_fail(f"{label}: invalid JSON ({exc})")
    except OSError as exc:
        guard_fail(f"{label}: cannot read ({exc})")
    if not isinstance(data, dict):
        guard_fail(f"{label}: top level must be a JSON object, found {type(data).__name__}")
    return data


def non_empty_str(obj: dict, key: str, label: str) -> str:
    value = obj.get(key)
    if not isinstance(value, str) or not value.strip():
        guard_fail(f"{label}: {key} must be a non-empty string, found {value!r}")
    return value


def read_source(repo_root: str) -> dict:
    plugin = read_json_object(os.path.join(repo_root, "plugin.json"), "plugin.json")
    non_empty_str(plugin, "name", "plugin.json")
    non_empty_str(plugin, "version", "plugin.json")
    non_empty_str(plugin, "description", "plugin.json")
    if not KEBAB.fullmatch(plugin["name"]):
        guard_fail(f"plugin.json: name {plugin['name']!r} must be kebab-case")
    author = plugin.get("author")
    if author is not None:
        if not isinstance(author, dict):
            guard_fail(f"plugin.json: author must be an object, found {type(author).__name__}")
        non_empty_str(author, "name", "plugin.json author")
    extensions = plugin.get("extensions")
    if extensions is not None and not isinstance(extensions, dict):
        guard_fail(f"plugin.json: extensions must be an object, found {type(extensions).__name__}")
    return plugin


def codex_display_name(plugin: dict) -> str:
    """Codex presentation label: documented nesting first, flat shape as fallback."""
    openai = (plugin.get("extensions") or {}).get("com.openai") or {}
    if not isinstance(openai, dict):
        guard_fail("plugin.json: extensions['com.openai'] must be an object")
    interface = openai.get("interface")
    if isinstance(interface, dict) and interface.get("displayName"):
        return str(interface["displayName"])
    return str(openai.get("displayName") or plugin["name"])


def codex_category(plugin: dict) -> str:
    """Codex marketplace entry category, taken from the manifest when present."""
    openai = (plugin.get("extensions") or {}).get("com.openai") or {}
    if isinstance(openai, dict):
        interface = openai.get("interface")
        if isinstance(interface, dict) and interface.get("category"):
            return str(interface["category"])
        if openai.get("category"):
            return str(openai["category"])
    return CODEX_CATEGORY


