# Entry point
# ---------------------------------------------------------------------------


def run(args: argparse.Namespace) -> int:
    repo_root = os.path.abspath(args.repo_root)
    if not os.path.isdir(repo_root):
        guard_fail(f"--repo-root {repo_root}: not a directory")

    plugin = read_source(repo_root)
    expected = build_expected(plugin)

    if args.write:
        written = write_all(repo_root, expected)
        print("wrote " + ", ".join(written) if written else "nothing to write; all manifests already in sync")
        problems = check_drift(repo_root, expected) + check_surface(repo_root) + validate(repo_root, plugin)
        if problems:
            print(f"manifest guard: {len(problems)} problem(s) remain after writing")
            for problem in problems:
                print(f"  - {problem}")
            return 1
        return 0

    do_check = args.check or not args.validate
    do_validate = args.validate or not args.check

    problems: list[str] = []
    if do_check:
        problems += check_drift(repo_root, expected)
        problems += check_surface(repo_root)
    if do_validate:
        problems += validate(repo_root, plugin)

    if problems:
        print(f"manifest guard: {len(problems)} problem(s)")
        for problem in problems:
            print(f"  - {problem}")
        return 1

    print(f"manifest guard: OK ({len(expected)} generated file(s) in sync with plugin.json {plugin['version']})")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Sync and verify client manifests against plugin.json")
    parser.add_argument("--write", action="store_true", help="rewrite generated files from plugin.json")
    parser.add_argument("--check", action="store_true", help="drift check only")
    parser.add_argument("--validate", action="store_true", help="structural validation only")
    parser.add_argument("--repo-root", default=REPO_ROOT)
    args = parser.parse_args()

    if args.write and (args.check or args.validate):
        parser.error("--write cannot be combined with --check/--validate: --write already re-checks after writing")

    try:
        return run(args)
    except GuardInputError as exc:
        print(f"manifest guard: {exc}")
        return 2
    except (OSError, UnicodeDecodeError, json.JSONDecodeError, AttributeError, TypeError, KeyError, ValueError) as exc:
        # Malformed repository state must read as a guard message, never a traceback.
        print(f"manifest guard: unexpected input ({type(exc).__name__}: {exc})")
        return 2


